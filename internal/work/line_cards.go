// Only public HTTPS assets/links belong in LINE cards. No credentials or private
// storage paths are exposed. Existing message content remains authoritative.
func publicCardURL(raw string) string {
	u, err := url.Parse(raw)
	if err != nil || u.Scheme != "https" || u.Hostname() == "" || u.User != nil {
		return ""
	}
	return u.String()
}

func (l *LinePush) messageCard(message string) map[string]any {
	title, detail, worker := "มีรายการอัปเดต", message, false
	labels := []struct {
		key, title, detail string
		worker             bool
	}{
		{"schedule", "ตารางงานอัปเดต", "มีการเปลี่ยนแปลงตารางงาน กรุณาเปิดระบบเพื่อตรวจสอบรายละเอียด", true},
		{"leave_review", "ผลพิจารณาใบลา", "ผลพิจารณาใบลาพร้อมให้ตรวจสอบแล้ว", true},
		{"leave", "มีคำขอลาใหม่", "กรุณาตรวจสอบคำขอลาและจัดคนทดแทนตามความเหมาะสม", false},
		{"approval_needed", "รออนุมัติจัดซื้อ", "มีคำขอจัดซื้อรอการพิจารณา", false},
		{"purchase_funding", "รอเงินจัดซื้อ", "มีรายการจัดซื้อรอการจัดสรรเงิน", false},
		{"replacement_needed", "ต้องจัดคนทดแทน", "กรุณาตรวจสอบกะงานที่ต้องจัดคนทดแทน", false},
		{"funded", "บันทึกการโอนเงินแล้ว", "เปิดระบบเพื่อตรวจสอบข้อมูลการจัดซื้อ", false},
		{"request", "มีคำขออุปกรณ์ใหม่", "กรุณาตรวจสอบรายการและจำนวนอุปกรณ์ที่แจ้งขอ", false},
		{"request_review", "ผลพิจารณาคำขออุปกรณ์", "เปิดระบบเพื่อตรวจสอบผลพิจารณาคำขอ", true},
		{"payroll", "ข้อมูลค่าจ้างอัปเดต", "เปิดระบบเพื่อตรวจสอบรายละเอียดค่าจ้างของคุณ", true},
	}
	for _, item := range labels {
		if message == "Chaum: "+item.key+" updated. Please open the app to view details." {
			title, detail, worker = item.title, item.detail, item.worker
			break
		}
	}
	if strings.HasPrefix(message, "Chaum: ส่งมอบอุปกรณ์คำขอ ") {
		title, detail, worker = "ส่งมอบอุปกรณ์แล้ว", strings.TrimPrefix(message, "Chaum: "), true
	}
	for _, prefix := range []string{"Chaum: equipment request rejected. ", "Chaum: equipment request declined. "} {
		if strings.HasPrefix(message, prefix) {
			title, detail, worker = "คำขออุปกรณ์ไม่ได้รับอนุมัติ", "เหตุผล: "+strings.TrimPrefix(message, prefix), true
		}
	}
	for _, decision := range []struct{ state, title string }{
		{"approved", "ใบลาได้รับอนุมัติแล้ว"},
		{"rejected", "ใบลาไม่ได้รับอนุมัติ"},
	} {
		prefix := "Chaum: leave " + decision.state + ".\n"
		if strings.HasPrefix(message, prefix) {
			title, detail, worker = decision.title, cardLeaveDetails(strings.TrimPrefix(message, prefix)), true
		}
	}
	if strings.HasPrefix(message, "Chaum: worker project summary.\n") {
		title, detail, worker = "สรุปงานของคุณในโครงการ", strings.TrimPrefix(message, "Chaum: worker project summary.\n"), true
	}
	for _, event := range []struct{ prefix, title string }{
		{"Chaum: schedule details.\n", "ตารางงานของคุณอัปเดต"},
		{"Chaum: payroll calculated.\n", "ประมวลผลค่าจ้างแล้ว"},
		{"Chaum: payroll paid.\n", "ยืนยันการจ่ายค่าจ้างแล้ว"},
		{"Chaum: equipment approved.\n", "คำขอจัดซื้อได้รับอนุมัติ"},
		{"Chaum: equipment rejected.\n", "คำขอจัดซื้อไม่ได้รับอนุมัติ"},
	} {
		if strings.HasPrefix(message, event.prefix) {
			title, detail, worker = event.title, strings.TrimPrefix(message, event.prefix), true
		}
	}
	link := publicCardURL(l.DashboardURL)
	if worker {
		link = publicCardURL(l.WorkerURL)
	}
	if strings.HasPrefix(message, "สรุปผลการดำเนินงานโครงการ ") {
		title = "สรุปผลการดำเนินงาน"
		// The summary URL is generated by the business service with its TOR/date
		// filters. Preserve it exactly; do not replace it with a generic entry URL.
		if pos := strings.LastIndex(message, "\n"); pos >= 0 {
			if report := publicCardURL(message[pos+1:]); report != "" {
				link, detail = report, message[:pos]
			}
		}
	}
	alt := []rune(title + ": " + detail)
	if len(alt) > 400 {
		alt = alt[:400]
	}
	bubble := map[string]any{"type": "bubble", "body": map[string]any{"type": "box", "layout": "vertical", "spacing": "md", "paddingAll": "20px", "contents": []map[string]any{
		{"type": "text", "text": "ชะอุ่ม · CHAUM", "size": "xs", "color": "#28664F", "weight": "bold"},
		{"type": "text", "text": title, "size": "lg", "weight": "bold", "wrap": true, "color": "#24352D"},
		{"type": "text", "text": detail, "size": "sm", "wrap": true, "color": "#59685F"},
	}}}
	logo := publicCardURL(l.LogoURL)
	if logo == "" {
		if base, err := url.Parse(publicCardURL(l.DashboardURL)); err == nil && base.Host != "" {
			logo = base.ResolveReference(&url.URL{Path: "/brand/chaum-logo.png"}).String()
		}
	}
	if logo != "" {
		bubble["hero"] = map[string]any{"type": "box", "layout": "vertical", "paddingAll": "16px", "backgroundColor": "#F5F8F4", "contents": []map[string]any{{"type": "image", "url": logo, "size": "full", "aspectRatio": "3:1", "aspectMode": "fit"}}}
	}
	actionLabel := "เปิดดูรายละเอียด"
	if worker {
		actionLabel = "เปิด Mini App"
	}
	if link != "" {
		bubble["footer"] = map[string]any{"type": "box", "layout": "vertical", "paddingAll": "16px", "contents": []map[string]any{{"type": "button", "style": "primary", "color": "#28664F", "action": map[string]any{"type": "uri", "label": actionLabel, "uri": link}}}}
	}
	return map[string]any{"type": "flex", "altText": string(alt), "contents": bubble}
}

func cardThaiDate(value string) string {
	date, err := time.Parse("2006-01-02", value)
	if err != nil {
		return value
	}
	months := []string{"ม.ค.", "ก.พ.", "มี.ค.", "เม.ย.", "พ.ค.", "มิ.ย.", "ก.ค.", "ส.ค.", "ก.ย.", "ต.ค.", "พ.ย.", "ธ.ค."}
	return date.Format("02") + " " + months[int(date.Month())-1] + " " + strconv.Itoa(date.Year()+543)
}
func cardLeaveDetails(value string) string {
	lines := strings.Split(value, "\n")
	for i, line := range lines {
		if strings.HasPrefix(line, "วันที่ลา: ") {
			lines[i] = "วันที่ลา: " + cardThaiDate(strings.TrimPrefix(line, "วันที่ลา: "))
		}
		if strings.HasPrefix(line, "เลขใบลา: LEAVE-") {
			raw := strings.TrimPrefix(line, "เลขใบลา: LEAVE-")
			if _, err := uuid.Parse(raw); err == nil {
				lines[i] = "เลขอ้างอิงย่อ: LEAVE-" + raw[:8]
			}
		}
	}
	return strings.Join(lines, "\n")
}
